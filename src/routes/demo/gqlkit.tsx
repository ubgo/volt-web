import { useQuery } from "@tanstack/react-query"
import { createFileRoute } from "@tanstack/react-router"
import { CheckCircle2, Database, XCircle } from "lucide-react"
import { AdminShell, PageHeader } from "@/components/admin-shell"
import { StatusBadge } from "@/demo/form/form-kit"
// The generated SDK — proves the typed builder API is wired. Every real query
// goes through `new QueryRoot(createApiClient()).<field>().select(…).execute()`.
import { QueryRoot } from "@/generated/sdk/queries"
import { createAnonClient } from "@/lib/gql-clients"
import { seo } from "@/lib/seo"

export const Route = createFileRoute("/demo/gqlkit")({
	component: GqlkitDemo,
	head: () => seo({ title: "GraphQL (gqlkit)" }),
})

const ENDPOINT =
	import.meta.env.VITE_GRAPHQL_URL ?? "https://volt-api.localhost/api/query"

function GqlkitDemo() {
	// Live connectivity check against the GraphQL backend via the gqlkit-ts
	// runtime client. `__typename` is always valid, so this proves the
	// client → endpoint round-trip regardless of the app's schema.
	const ping = useQuery({
		queryKey: ["gqlkit", "typename"],
		queryFn: () =>
			createAnonClient().execute<{ __typename: string }>("{ __typename }"),
		retry: false,
	})

	const connected = !!ping.data && !ping.error

	return (
		<AdminShell>
			<div className="px-6 py-6 max-w-3xl">
				<PageHeader
					icon={<Database />}
					title="GraphQL (gqlkit)"
					subtitle="Typed GraphQL SDK generated by gqlkit — no graphql-codegen"
				/>

				<div className="space-y-6">
					{/* Live connection */}
					<section>
						<h2 className="text-[13px] font-medium mb-2">Connection</h2>
						<div className="rounded-md border border-border bg-background p-4 space-y-3">
							<Row label="Endpoint">
								<code className="rounded bg-muted px-1.5 py-0.5 font-mono text-[12px]">
									{ENDPOINT}
								</code>
							</Row>
							<Row label="Status">
								{ping.isLoading ? (
									<span className="text-[13px] text-muted-foreground">
										Connecting…
									</span>
								) : connected ? (
									<span className="inline-flex items-center gap-1.5 text-[13px] text-emerald-600 dark:text-emerald-400">
										<CheckCircle2 className="size-3.5" />
										Connected
									</span>
								) : (
									<span className="inline-flex items-center gap-1.5 text-[13px] text-destructive">
										<XCircle className="size-3.5" />
										Unreachable
									</span>
								)}
							</Row>
							<Row label="Query.__typename">
								<code className="rounded bg-muted px-1.5 py-0.5 font-mono text-[12px]">
									{ping.data?.__typename ?? (ping.error ? "—" : "…")}
								</code>
							</Row>
							{ping.error ? (
								<p className="text-[11px] text-muted-foreground">
									{(ping.error as Error).message}. Set{" "}
									<code className="font-mono">VITE_GRAPHQL_URL</code> and make
									sure the backend allows this origin (CORS).
								</p>
							) : null}
						</div>
					</section>

					{/* Generated SDK */}
					<section>
						<h2 className="text-[13px] font-medium mb-2">Generated SDK</h2>
						<div className="rounded-md border border-border bg-background p-4 space-y-3">
							<Row label="Runtime">
								<StatusBadge label="gqlkit-ts" tone="success" />
							</Row>
							<Row label="SDK location">
								<code className="font-mono text-[12px]">src/generated/sdk</code>
							</Row>
							<Row label="Roots">
								<span className="text-[13px] tabular-nums">
									QueryRoot · MutationRoot
								</span>
							</Row>
							<Row label="Regenerate">
								<code className="rounded bg-muted px-1.5 py-0.5 font-mono text-[12px]">
									task gqlkit:all
								</code>
							</Row>
						</div>
					</section>

					{/* Usage pattern */}
					<section>
						<h2 className="text-[13px] font-medium mb-2">Usage pattern</h2>
						<pre className="rounded-md border border-border bg-muted/40 p-4 text-[12px] font-mono overflow-x-auto leading-relaxed">
							{`import { QueryRoot } from "@/generated/sdk/queries"
import { createApiClient } from "@/lib/gql-clients"

const data = await new QueryRoot(createApiClient())
  .pimProducts()
  .workspaceId(workspaceId)
  .select((f) => f.total().edges((e) =>
    e.node((n) => n.id().title().status())))
  .execute()   // fully typed — no inline GraphQL strings`}
						</pre>
						<p className="mt-2 text-[11px] text-muted-foreground">
							Fluent, typesafe builders per query/mutation. The{" "}
							<code className="font-mono">
								{String(
									typeof QueryRoot === "function"
										? QueryRoot.name
										: "QueryRoot",
								)}
							</code>{" "}
							class is generated from the backend schema — change the schema,
							run <code className="font-mono">task gqlkit:all</code>, done.
						</p>
					</section>
				</div>
			</div>
		</AdminShell>
	)
}

function Row({
	label,
	children,
}: {
	label: string
	children: React.ReactNode
}) {
	return (
		<div className="flex items-center gap-4">
			<div className="w-32 shrink-0 text-[12px] text-muted-foreground">
				{label}
			</div>
			<div className="min-w-0">{children}</div>
		</div>
	)
}
